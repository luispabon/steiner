package licensescan

import (
	"fmt"
	"sort"
	"strings"
)

// Render returns the notices document for report. The output is deterministic:
// modules and their files are sorted by path, and the byte sequence depends
// only on the report contents.
func Render(report *Report) []byte {
	var b strings.Builder
	b.WriteString("# Third-party notices\n\n")
	b.WriteString("Steiner is licensed under the [Apache License 2.0](LICENSE). Its release\n")
	b.WriteString("binaries statically link the Go modules and the Go standard library listed\n")
	b.WriteString("below, and each entry reproduces the upstream license and notice files that\n")
	b.WriteString("ship with that code.\n\n")
	b.WriteString("This file is generated by `make notices` for the release build matrix (")
	b.WriteString(platformList())
	b.WriteString(") and must not be edited by hand.\n\n")
	b.WriteString("The detected license names are a heuristic summary; the reproduced text below\n")
	b.WriteString("is authoritative.\n\n")

	modules := sortedModules(report.Modules)
	renderSummary(&b, modules)

	b.WriteString("## Go standard library and runtime (")
	b.WriteString(report.GoVersion)
	b.WriteString(")\n\n")
	for _, file := range sortedFiles(report.GoFiles) {
		renderFile(&b, file)
	}

	for _, module := range modules {
		b.WriteString("## ")
		b.WriteString(module.Path)
		b.WriteString(" ")
		b.WriteString(module.Version)
		b.WriteString("\n\n")
		b.WriteString("Licenses detected: ")
		b.WriteString(strings.Join(module.Licenses, ", "))
		b.WriteString("\n\n")
		for _, file := range sortedFiles(module.Files) {
			renderFile(&b, file)
		}
	}
	return []byte(strings.TrimRight(b.String(), "\n") + "\n")
}

// renderSummary writes the module count per detected license name.
func renderSummary(b *strings.Builder, modules []Module) {
	counts := map[string]int{}
	for _, module := range modules {
		for _, license := range module.Licenses {
			counts[license]++
		}
	}
	names := make([]string, 0, len(counts))
	for name := range counts {
		names = append(names, name)
	}
	sort.Strings(names)

	b.WriteString("## Summary\n\n")
	b.WriteString("| License | Modules |\n")
	b.WriteString("| --- | --- |\n")
	for _, name := range names {
		fmt.Fprintf(b, "| %s | %d |\n", name, counts[name])
	}
	b.WriteString("\n")
}

// renderFile writes one file heading and its fenced text.
func renderFile(b *strings.Builder, file LicenseFile) {
	b.WriteString("### ")
	b.WriteString(file.Path)
	b.WriteString("\n\n")
	writeFenced(b, file.Text)
	b.WriteString("\n")
}

// writeFenced writes text as a `text` fenced code block using a fence longer
// than any backtick run in text.
func writeFenced(b *strings.Builder, text string) {
	text = strings.TrimRight(text, "\n")
	fence := strings.Repeat("`", fenceLength(text))
	b.WriteString(fence)
	b.WriteString("text\n")
	b.WriteString(text)
	b.WriteString("\n")
	b.WriteString(fence)
	b.WriteString("\n")
}

// fenceLength returns the fence length needed for text: one more backtick than
// its longest run, and never fewer than three.
func fenceLength(text string) int {
	longest, run := 0, 0
	for _, r := range text {
		if r == '`' {
			run++
			if run > longest {
				longest = run
			}
			continue
		}
		run = 0
	}
	if longest < 2 {
		return 3
	}
	return longest + 1
}

// platformList returns the release matrix as a comma-separated list.
func platformList() string {
	names := make([]string, 0, len(ReleasePlatforms))
	for _, platform := range ReleasePlatforms {
		names = append(names, platform.String())
	}
	return strings.Join(names, ", ")
}

// sortedModules returns a copy of modules sorted by path.
func sortedModules(modules []Module) []Module {
	sorted := append([]Module(nil), modules...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Path < sorted[j].Path })
	return sorted
}

// sortedFiles returns a copy of files sorted by path.
func sortedFiles(files []LicenseFile) []LicenseFile {
	sorted := append([]LicenseFile(nil), files...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Path < sorted[j].Path })
	return sorted
}
